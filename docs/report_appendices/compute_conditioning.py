"""
compute_conditioning.py
=======================
Read-only diagnostic for docs/complete_research_report.md, Section 14. Fits B2/B3/B4/R1 on the
committed in-sample development design (last 2019 row as refit origin, 2,231 supervised rows,
lambda = 0.01 as in the original Stage 7 / Gate D configuration) with the current converged
optimiser, then reports the exact Hessian of the penalised objective at the optimum in

  (a) the ORIGINAL parameterisation theta = (w_mu, b_mu, w_sig, b_sig, raw_nu), and
  (b) the PRECONDITIONED parameterisation used by the fix (phi_mu = theta_mu / sd(y)).

No file other than docs/report_appendices/conditioning.md is written.
Run from the repository root: python docs/report_appendices/compute_conditioning.py
"""
import sys

sys.path.insert(0, ".")
import numpy as np
import pandas as pd
import torch
import torch.nn.functional as F

from src.models.density_models import StudentTRegression, _student_t_log_lik
from src.models.walk_forward_pipeline import build_refit_inputs

OUT = "docs/report_appendices/conditioning.md"
LAM = 0.01


def hessian(fn, x0):
    x = torch.tensor(x0, dtype=torch.float64, requires_grad=True)
    return torch.autograd.functional.hessian(fn, x).numpy()


def main():
    dev = pd.read_csv("output/stage7_datasets/spx_stage7_operational_development_2010_2019.csv")
    r = build_refit_inputs(dev, len(dev) - 1, len(dev))
    y = torch.as_tensor(r["y_train"])
    s = float(np.std(r["y_train"], ddof=1))
    rows = []
    for name, key in [("B2", "Q_train_scaled"), ("B3", "X_train_scaled"), ("B4", "QX_train_scaled"), ("R1", "QXpi_train")]:
        X = r[key]
        d = X.shape[1]
        m = StudentTRegression(in_features=d, l2_reg=LAM).fit(X, r["y_train"])
        Xt = torch.as_tensor(X)
        th0 = np.concatenate([m.fc_mu.weight.detach().numpy().ravel(), m.fc_mu.bias.detach().numpy(),
                              m.fc_sig.weight.detach().numpy().ravel(), m.fc_sig.bias.detach().numpy(),
                              m.raw_nu.detach().numpy()])

        def obj(th, scale=1.0):
            wm, bm = th[:d] * scale, th[d] * scale
            ws, bs, rn = th[d + 1:2 * d + 1], th[2 * d + 1], th[2 * d + 2]
            mu = Xt @ wm + bm
            sig = F.softplus(Xt @ ws + bs) + 1e-4
            nu = F.softplus(rn) + 2.1
            return -torch.mean(_student_t_log_lik(y, mu, sig, nu)) + LAM * (wm @ wm + ws @ ws)

        H_theta = hessian(lambda th: obj(th), th0)
        phi0 = th0.copy()
        phi0[: d + 1] /= s
        H_phi = hessian(lambda th: obj(th, s), phi0)
        ev_t, ev_p = np.linalg.eigvalsh(H_theta), np.linalg.eigvalsh(H_phi)
        diag = np.diag(H_theta)
        rows.append((name, d, 2 * d + 3, ev_t.min(), ev_t.max(), ev_t.max() / ev_t.min(), ev_p.min(), ev_p.max(),
                     ev_p.max() / ev_p.min(), diag[d], np.median(diag[d + 1:2 * d + 2]), diag[-1],
                     m.fit_report_["nu"], m.fit_report_["penalized_loss"]))
    L = ["# Appendix C - Hessian conditioning of the Student-t regression objective", "",
         "Generated by `docs/report_appendices/compute_conditioning.py` (read-only). In-sample development design "
         f"(2,231 rows, refit origin 2019-12-31), lambda = {LAM}, converged fits; sd(y_train) = {s:.6f}. "
         "Exact Hessians of the penalised objective at the optimum via autograd.", "",
         "| model | inputs d | parameters | theta: min eig | theta: max eig | theta: condition | phi: min eig | phi: max eig | "
         "phi: condition | H[b_mu,b_mu] | median H[sigma-weights] | H[raw_nu] | nu | penalised NLL |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for t in rows:
        L.append("| " + " | ".join([t[0], str(t[1]), str(t[2])] + [f"{v:.3g}" for v in t[3:12]] + [f"{t[12]:.3f}", f"{t[13]:.6f}"]) + " |")
    L += ["", "theta = original parameterisation (location weights in return units); phi = location weights divided by "
          "sd(y). The location curvature scales like 1/sigma^2 (sigma ~ 0.009), so theta-space location eigenvalues are of "
          "order 1e4 while raw_nu curvature is of order 1e-3; preconditioning rescales the location block by s^2."]
    open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
